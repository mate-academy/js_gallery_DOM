'use strict';

/**
 * реалізація галереї з використанням делегування подій.
 * ми вішаємо один обробник на батьківський елемент 'thumbs',
 * замість того, щоб додавати його до кожного посилання окремо.
 */
// шукаємо контейнер з мініатюрами (батьківський елемент)
const thumbs = document.getElementById('thumbs');
// шукаємо елемент великої картинки в DOM
const largeImg = document.getElementById('largeImg');

// перевіряємо, чи існують обидва елементи на сторінці, щоб уникнути помилок
if (thumbs && largeImg) {
  // вішаємо слухач подій на весь контейнер
  thumbs.addEventListener('click', (evnt) => {
    // юзаємо .closest('a'), щоб знайти найближче посилання.
    // спрацює, навіть якщо юзер натиснув на <img> всередині <a>.
    const link = evnt.target.closest('a');

    // перевіряємо, чи клік дійсно відбувся по посиланню всередині списку.
    // якщо клікнули на порожнє місце в <ul>, метод поверне null, і ми вийдемо.
    if (!link) {
      return;
    }

    // відміняємо стандартну поведінку браузера.
    // без цього браузер відкриє картинку окремою сторінкою
    // (перейде за посиланням).
    evnt.preventDefault();

    // оновлюємо атрибут 'src' великої картинки.
    // беремо значення з атрибута 'href' того посилання, по якому був клік.
    largeImg.src = link.href;
    // додатково оновлюємо 'alt' для доступності,
    // використовуючи заголовок посилання

    largeImg.alt = link.title;
  });
}
